def _df() -> pd.DataFrame:
    rows = []
    for t, o, h, l, c, v in BARS:
        ts = dt.datetime.fromtimestamp(t, tz=UTC).replace(tzinfo=None)  # tz-naive UTC, bar open
        rows.append(dict(symbol="QQQ", asset_class="equity", timeframe="30m",
                         ts_utc=ts, open=float(o), high=float(h), low=float(l),
                         close=float(c), volume=float(v), trade_count=None,
                         vwap=None, adjusted=True))
    return pd.DataFrame(rows)


